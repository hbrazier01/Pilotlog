#!/usr/bin/env node
// Generate contract/cfi_endorse.compact for one WebAuthn environment (RP ID + origin are compile-time
// constants of the circuit: the clientDataJSON suffix length is part of the circuit's shape).
//   CFI_RP_ID=cfi-passkey-staging-staging.up.railway.app CFI_ORIGIN=https://cfi-passkey-staging-staging.up.railway.app \
//     node scripts/gen-contract.mjs
// Writes contract/cfi_endorse.compact and contract/env.json ({ name, rpId, origin }). compile.sh copies env.json
// into contract/managed/ so every off-chain helper uses the RP ID/origin the compiled circuit enforces.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

// Without env vars, regenerate for the environment recorded in contract/env.json (template edits only).
const prev = existsSync(new URL('../contract/env.json', import.meta.url)) ? JSON.parse(readFileSync(new URL('../contract/env.json', import.meta.url), 'utf8')) : {};
const rpId = process.env.CFI_RP_ID ?? prev.rpId, origin = process.env.CFI_ORIGIN ?? prev.origin, name = process.env.CFI_ENV_NAME ?? prev.name ?? 'custom';
if (!rpId || !origin) { console.error('set CFI_RP_ID and CFI_ORIGIN'); process.exit(2); }
if (!/^[a-z0-9.-]+$/.test(rpId) || rpId.length > 253) throw new Error(`bad RP ID ${rpId}`);
const u = new URL(origin);
if (u.protocol !== 'https:' && !(u.protocol === 'http:' && u.hostname === 'localhost')) throw new Error('origin must be https (or http://localhost)');
if (u.origin !== origin) throw new Error(`origin must be a bare origin (got ${origin}, normalised ${u.origin})`);
if (!(u.hostname === rpId || u.hostname.endsWith('.' + rpId))) throw new Error(`origin host ${u.hostname} is not within RP ID ${rpId}`);

const suffix = `","origin":"${origin}","crossOrigin":false}`;
const compactLiteral = suffix.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
const dir = new URL('../contract/', import.meta.url);
const src = readFileSync(new URL('cfi_endorse.compact.in', dir), 'utf8')
  .replaceAll('@@CD_SUFFIX_LEN@@', String(Buffer.byteLength(suffix)))
  .replaceAll('@@CD_SUFFIX@@', compactLiteral)
  .replaceAll('@@RP_ID_LEN@@', String(Buffer.byteLength(rpId)))
  .replaceAll('@@RP_ID@@', rpId);
if (src.includes('@@')) throw new Error('unsubstituted placeholder');
writeFileSync(new URL('cfi_endorse.compact', dir), `// GENERATED by scripts/gen-contract.mjs from cfi_endorse.compact.in for ${name} (${origin}). Do not edit.\n` + src);
writeFileSync(new URL('env.json', dir), JSON.stringify({ name, rpId, origin, cdSuffixLen: Buffer.byteLength(suffix) }, null, 2) + '\n');
console.log(`generated cfi_endorse.compact for ${name}: rpId=${rpId} origin=${origin} cdSuffix=${Buffer.byteLength(suffix)} bytes`);
